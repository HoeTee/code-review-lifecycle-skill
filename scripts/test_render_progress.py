"""Check progress-state invariants that prevent misleading user actions."""
from copy import deepcopy
from hashlib import sha256
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
from tempfile import TemporaryDirectory
import unittest
from unittest.mock import patch

from render_progress import render, validate
from answer_progress import build_draft, render_answer_progress


EXAMPLE = Path(__file__).resolve().parents[1] / "assets/progress.example.json"
SHOWCASE = Path(__file__).resolve().parents[1] / "docs/showcase/export-review.md"
SCRIPTS = Path(__file__).resolve().parent
PROJECT_URL = "https://github.com/HoeTee/code-review-lifecycle-skill"
RENDERER = SCRIPTS / "vendor/answer-me-with-html/am.mjs"
UPSTREAM_RENDERER_SHA256 = "5e08fda8e976927b16596624cf605e5aadd77828ee690a412b5a9a96584d4f2c"


class ProgressStateTests(unittest.TestCase):
    def setUp(self):
        self.state = json.loads(EXAMPLE.read_text(encoding="utf-8"))

    def test_completed_snapshot_preserves_unstarted_phases_and_evidence_time(self):
        self.state["checks"] = [{"title": "Earlier check", "status": "passed", "observed_at": "2025-12-31T08:00:00Z"}]
        original = deepcopy(self.state)
        page = render(self.state)
        self.assertEqual(self.state, original)
        payload = page.split('<script id="task-state" type="application/json">', 1)[1].split('</script>', 1)[0]
        restored = json.loads(payload)
        self.assertEqual(restored["phases"][2]["status"], "not_started")
        self.assertEqual(restored["checks"][0]["observed_at"], "2025-12-31T08:00:00Z")

    def test_legacy_snapshot_still_renders(self):
        legacy_ids = ("pre_pr", "in_pr", "post_pr")
        self.state["phase"] = "in_pr"
        self.state["goal"].update(mode="scoped", scope_confirmation="Review the local changes")
        for phase, legacy_id in zip(self.state["phases"], legacy_ids):
            phase["id"] = legacy_id
        validate(self.state)
        self.assertIn("当前阶段: PR 中", build_draft(self.state, EXAMPLE))
        self.assertIn("task-state", render(self.state))

    def test_active_phase_matches_the_snapshot(self):
        self.state["phase"] = "in_pr"
        with self.assertRaisesRegex(ValueError, "matching active phase"):
            validate(self.state)

    def test_native_renderer_links_to_the_project(self):
        header = render(self.state).split("<header>", 1)[1].split("</header>", 1)[0]
        self.assertIn("Generated by", header)
        self.assertIn(">code-review-lifecycle-skill</a>", header)
        self.assertIn(">★ Star on GitHub</a>", header)
        self.assertEqual(header.count(f'href="{PROJECT_URL}"'), 2)

    def test_waiting_requires_an_action_with_impact_and_reply(self):
        self.state["status"] = "waiting_user"
        with self.assertRaises(ValueError):
            validate(self.state)
        self.state["user_actions"] = [{"question": "Choose target", "recommendation": "Reuse current target", "impact": "Changes the review scope", "instruction": "Reuse current target"}]
        validate(self.state)
        self.state["status"] = "completed"
        with self.assertRaises(ValueError):
            validate(self.state)

    def test_blocked_requires_a_concrete_owner_and_recovery_action(self):
        self.state["status"] = "blocked"
        with self.assertRaises(ValueError):
            validate(self.state)
        self.state["issues"] = [{"blocking": True, "title": "Runner unavailable", "owner": "Platform operator", "impact": "CI cannot start", "next_action": "Restore runner access"}]
        validate(self.state)

    def test_rejects_executable_links_and_escapes_embedded_script_terminator(self):
        self.state["links"] = [{"label": "bad", "href": "javascript:alert(1)"}]
        with self.assertRaises(ValueError):
            validate(self.state)
        self.state["links"] = []
        self.state["title"] = "</script><script>alert(1)</script>"
        page = render(self.state)
        self.assertNotIn(self.state["title"], page)
        self.assertIn("\\u003c/script\\u003e", page)

    def test_finished_snapshot_cannot_claim_automatic_background_continuation(self):
        self.state["next_step"]["kind"] = "automatic"
        with self.assertRaises(ValueError):
            validate(self.state)

    def test_end_to_end_goal_cannot_finish_after_only_local_checks(self):
        self.state["goal"]["mode"] = "end_to_end"
        self.state["goal"]["criteria"].append({"id": "pull_request", "title": "PR created", "status": "pending"})
        with self.assertRaisesRegex(ValueError, "required stages remain pending"):
            validate(self.state)
        self.state["status"] = "running"
        validate(self.state)

    def test_narrowed_goal_requires_user_scope_and_passed_criteria_need_evidence(self):
        self.state["goal"]["mode"] = "scoped"
        with self.assertRaisesRegex(ValueError, "explicit user instruction"):
            validate(self.state)
        self.state["goal"]["mode"] = "end_to_end"
        del self.state["goal"]["criteria"][0]["evidence"]
        with self.assertRaisesRegex(ValueError, "require evidence"):
            validate(self.state)

    def test_information_request_can_use_direct_reply_without_a_dummy_command(self):
        self.state["status"] = "waiting_user"
        self.state["user_actions"] = [{"question": "Where is the private dependency?", "recommendation": "Use its existing source", "impact": "CI cannot install it", "reply_hint": "Reply with the existing download instructions"}]
        validate(self.state)
        self.assertIn("existing download instructions", render(self.state))

    def test_delivery_text_evidence_renders_without_becoming_a_url(self):
        self.state["goal"]["criteria"] = [{"id": "delivery", "title": "Delivered", "status": "passed", "evidence": "Archive checksums verified in the recorded execution"}]
        validate(self.state)
        original = deepcopy(self.state)
        draft = build_draft(self.state, EXAMPLE)
        self.assertIn("Archive checksums verified", draft)
        self.assertNotIn("[打开交付包]", draft)
        self.assertEqual(self.state, original)

    def test_delivery_accepts_explicit_url_and_legacy_url_evidence(self):
        criterion = {"id": "delivery", "title": "Delivered", "status": "passed", "evidence": "Checksums verified", "evidence_href": "file:///C:/delivery/package.zip"}
        self.state["goal"]["criteria"] = [criterion]
        validate(self.state)
        self.assertIn("[打开交付包](file:///C:/delivery/package.zip)", build_draft(self.state, EXAMPLE))
        del criterion["evidence_href"]
        criterion["evidence"] = "https://example.com/package.zip"
        self.assertIn("[打开交付包](https://example.com/package.zip)", build_draft(self.state, EXAMPLE))
        criterion["evidence_href"] = "javascript:alert(1)"
        with self.assertRaises(ValueError):
            validate(self.state)

    def test_pr_table_separates_successful_checks_from_missing_human_and_merge(self):
        self.state["prs"] = [{"number": 7, "head": "1234567890", "ci_status": "success", "ai_status": "passed", "ai_completed_reviews": 2, "human_status": "pending", "merged": False}, {"number": 8, "head": "abcdef1234", "ci_status": "in_progress"}]
        original = deepcopy(self.state)
        draft = build_draft(self.state, EXAMPLE)
        self.assertIn("#7 | 12345678 | ok 通过 | ok 通过（2次） | warn 待处理 | warn 未合并", draft)
        self.assertIn("#8 | abcdef12 | warn 进行中 | warn 未记录 | warn 未记录 | warn 未记录", draft)
        self.assertEqual(self.state, original)

    def test_replan_and_final_review_have_different_visible_labels(self):
        self.state["status"] = "waiting_user"
        action = {"question": "Choose", "recommendation": "Concrete recommendation", "impact": "Explained impact", "reply_hint": "Reply here", "kind": "technical_replan"}
        self.state["user_actions"] = [action]
        validate(self.state)
        self.assertIn("当前关口：三轮后的方案决策", build_draft(self.state, EXAMPLE))
        action["kind"] = "final_review"
        self.assertIn("当前关口：合并前最终人工审核", build_draft(self.state, EXAMPLE))
        action["kind"] = "untyped_approval"
        with self.assertRaises(ValueError):
            validate(self.state)


    @unittest.skipUnless(shutil.which("node"), "Node.js is needed for the bundled renderer")
    def test_progress_cli_uses_the_bundled_renderer(self):
        with TemporaryDirectory() as directory:
            output = Path(directory) / "progress.html"
            self.run_render(
                sys.executable, "-B", str(SCRIPTS / "render_progress.py"),
                str(EXAMPLE), "--output", str(output),
                workdir=Path(directory),
            )
            page = output.read_text(encoding="utf-8")
            self.assertTrue('<meta name="generator" content="Answer me with HTML' in page, "Expected the bundled renderer")
            self.assertTrue(self.state["project"] in page, "The rendered progress page is missing the project name")
            evidence_panel = page.split('id="panel-D"', 1)[1].split("</section>", 1)[0]
            self.assertIn(self.state["goal"]["criteria"][0]["evidence"], evidence_panel)

    @unittest.skipUnless(shutil.which("node"), "Node.js is needed for the bundled renderer")
    def test_progress_cli_displays_review_evidence_and_its_link(self):
        with TemporaryDirectory() as directory:
            workdir = Path(directory)
            state_path = workdir / "state.json"
            output = workdir / "progress.html"
            criterion = self.state["goal"]["criteria"][0]
            criterion["evidence_href"] = "https://example.com/review-evidence"
            state_path.write_text(json.dumps(self.state), encoding="utf-8")
            self.run_render(
                sys.executable, "-B", str(SCRIPTS / "render_progress.py"),
                str(state_path), "--output", str(output), workdir=workdir,
            )
            page = output.read_text(encoding="utf-8")
            evidence_panel = page.split('id="panel-D"', 1)[1].split("</section>", 1)[0]
            self.assertIn(criterion["title"], evidence_panel)
            self.assertIn(criterion["evidence"], evidence_panel)
            self.assertIn('href="https://example.com/review-evidence"', evidence_panel)

    @unittest.skipUnless(shutil.which("node"), "Node.js is needed for the bundled renderer")
    def test_readme_example_keeps_project_links_after_a_panel_patch(self):
        with TemporaryDirectory() as directory:
            workdir = Path(directory)
            output = workdir / "review.html"
            cli = ("node", str(SCRIPTS / "render_html.mjs"))
            self.run_render(
                *cli, "render", str(SHOWCASE), "-o", str(output), "--no-open", workdir=workdir,
            )
            page = output.read_text(encoding="utf-8")
            self.assertTrue("<title>CSV export access review</title>" in page, "Expected the README example title")
            self.assert_project_credit(page)

            panel = workdir / "decision.md"
            panel.write_text("## D Human decision {span=2}\n\nThe reviewer approved the failure message.\n", encoding="utf-8")
            self.run_render(
                *cli, "patch", str(output), "--panel", "D", "--from", str(panel), "--no-open",
                workdir=workdir,
            )
            page = output.read_text(encoding="utf-8")
            visible = page.split('<textarea id="am-source"', 1)[0]
            self.assertIn("The reviewer approved the failure message.", visible)
            self.assertNotIn("Check the failure message", visible)
            self.assert_project_credit(page)

    def assert_project_credit(self, page: str):
        credit = page.split('<p class="am-colophon">', 1)[1].split("</p>", 1)[0]
        self.assertIn(">code-review-lifecycle-skill</a>", credit)
        self.assertIn(">★ Star on GitHub</a>", credit)
        self.assertEqual(credit.count(f'href="{PROJECT_URL}"'), 2)

    def test_renderer_bundle_matches_upstream_except_for_project_credit(self):
        bundle = RENDERER.read_bytes()
        branding = (
            (f'  const repo = "{PROJECT_URL}";'.encode("utf-8"),
             b'  const repo = "https://github.com/QingYunA/answer-me-with-html";'),
            (b'>code-review-lifecycle-skill</a>`;', b'>Answer me with HTML</a>`;'),
        )
        for project_text, upstream_text in branding:
            self.assertEqual(bundle.count(project_text), 1)
            bundle = bundle.replace(project_text, upstream_text)
        self.assertEqual(sha256(bundle).hexdigest(), UPSTREAM_RENDERER_SHA256)

    def test_renderer_bundle_contains_the_font(self):
        bundle = RENDERER.read_text(encoding="utf-8")
        self.assertTrue(
            'font-family: "Bangers";' in bundle and "data:font/woff2;base64," in bundle,
            "The renderer must include the bundled Bangers font",
        )

    def run_render(self, *command: str, workdir: Path):
        result = subprocess.run(
            command, cwd=workdir, env={**os.environ, "AM_HOME": str(workdir / "renderer")},
            capture_output=True, encoding="utf-8", errors="replace", timeout=30,
        )
        self.assertEqual(result.returncode, 0, result.stderr or result.stdout)

    def test_explicit_renderer_path_remains_supported(self):
        with TemporaryDirectory() as directory:
            workdir = Path(directory)
            custom_cli = workdir / "custom-renderer.mjs"
            custom_cli.touch()
            output = workdir / "progress.html"
            self.state["presentation"] = {"am_cli": str(custom_cli)}
            with patch("answer_progress.shutil.which", return_value="node"), patch(
                "answer_progress.subprocess.run"
            ) as run:
                render_answer_progress(self.state, EXAMPLE, output)
            self.assertEqual(run.call_args.args[0][1], str(custom_cli))


if __name__ == "__main__":
    unittest.main()
